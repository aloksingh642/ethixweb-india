/**
 * Resolved lazily rather than at module scope.
 *
 * This module is imported by both server components and the client Header, so
 * webpack compiles it into two layers. Keeping the `process.env` read inside a
 * function means it runs after the module graph is evaluated.
 *
 * ⚠ Never declare a binding called `process` in this file. A `const process`
 * here shadows Node's global within module scope and puts it in the temporal
 * dead zone, so `process.env` throws "Cannot access 'process' before
 * initialization" at build time. (This bit us once — hence `processSteps`.)
 */
export function siteUrl(): string {
  return process.env.NEXT_PUBLIC_SITE_URL || 'https://ethixweb.in';
}

